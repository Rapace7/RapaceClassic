  var KINDS = ['送驹', '驹形', '手番', '王的安全', '持驹', '禁手'];

  function selfTest(verbose) {
    var pass = 0, fail = 0;
    function padW(s, w) {
      var wide = 0, i, ch;
      s = String(s);
      for (i = 0; i < s.length; i++) { ch = s.charCodeAt(i); wide += (ch > 0x2e80) ? 2 : 1; }
      while (wide < w) { s += ' '; wide++; }
      return s;
    }
    function check(name, ok, msg) {
      if (ok) pass++; else fail++;
      if (!ok || verbose) console.log('  %s %s %s', ok ? '✓' : '✗', padW(name, 24), msg);
    }
    var seen = {}, dup = [], missing = [], badKind = [], short = [];
    var byKind = {};
    SHOGI_CHECKS.forEach(function (c) {
      if (seen[c.id]) dup.push(c.id);
      seen[c.id] = 1;
      ['id', 'kind', 'title', 'symptom', 'why', 'fix', 'tip'].forEach(function (k) {
        if (!c[k]) missing.push(c.id + '.' + k);
      });
      if (KINDS.indexOf(c.kind) < 0) badKind.push(c.id + '(' + c.kind + ')');
      byKind[c.kind] = (byKind[c.kind] || 0) + 1;
      if ((c.symptom || '').length < 30 || (c.fix || '').length < 30) short.push(c.id);
    });
    check('条目数', SHOGI_CHECKS.length >= 10, '共 ' + SHOGI_CHECKS.length + ' 条');
    check('id 不重复', dup.length === 0, dup.join('、') || '无重复');
    check('字段齐全', missing.length === 0, missing.join('、') || 'id/kind/title/symptom/why/fix/tip 都在');
    check('kind 合法', badKind.length === 0, badKind.join('、') || '六类之内');
    check('六类都有条目', KINDS.every(function (k) { return byKind[k] > 0; }),
      JSON.stringify(byKind));
    check('症状与做法不敷衍', short.length === 0, short.join('、') || '都 ≥30 字');
    console.log('');
    console.log('自检：通过 %d，失败 %d', pass, fail);
    return fail === 0;
  }

  var API = { CHECKS: SHOGI_CHECKS, KINDS: KINDS, selfTest: selfTest };
  if (typeof module !== 'undefined' && module.exports) module.exports = API;
  else global.ShogiSelfCheck = API;

  if (typeof require !== 'undefined' && typeof module !== 'undefined' && require.main === module) {
    process.exit(selfTest(process.argv.indexOf('-v') >= 0) ? 0 : 1);
  }
