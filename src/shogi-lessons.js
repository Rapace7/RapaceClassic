    var pass = 0, fail = 0;
    function padW(s, w) {
      var wide = 0, i, ch;
      s = String(s);
      for (i = 0; i < s.length; i++) { ch = s.charCodeAt(i); wide += (ch > 0x2e80) ? 2 : 1; }
      while (wide < w) { s += ' '; wide++; }
      return s;
    }
    function check(name, ok, msg) {
      if (ok) pass++; else fail++;
      console.log('  %s %s %s', ok ? '✓' : '✗', padW(name, 24), msg);
    }
    var seen = {}, dup = [], bad = [];
    SHOGI_LESSONS.forEach(function (l) {
      if (seen[l.id]) dup.push(l.id);
      seen[l.id] = 1;
      if (!l.t || !l.s || !l.key || !l.p || !l.p.length) bad.push(l.id);
      if ((l.p || []).join('').length < 200) bad.push(l.id + '(正文过短)');
    });
