/* 将棋 · 词典补充（棋盘图）
 *
 * 主数据 shogi-terms.js 里的正文不在这里改 —— 这个文件只负责「配图」，
 * 加载时挂到对应条目上（与围棋的 glossary-figs.js、国际象棋的 chess-terms2.js 同一套做法）。
 *
 * fig 的写法（与 shogi-board.js 一致）：
 *   { list:[[x,y,'s'|'g',类型,升变0|1],…], marks:[[x,y],…], cap:'说明' }
 *   x 从左到右 0–8（对应筋 ９→１，即 x=0 是 ９筋）
 *   y 从上到下 0–8（对应段 一→九，即 y=0 是一段）
 *   's' = 先手（下方）、'g' = 后手（上方）
 * 每张图都是**规则上成立的局面**，由 tools/audit.js 核对。
 */
(function (global) {
  'use strict';

  var API = global.ShogiTerms;
  var T = (API && API.TERMS) || (global.SHOGI_TERMS) || [];
  if (!T.length) return;

  var byName = {};
  T.forEach(function (x) { byName[x.t] = x; });

  function fig(name, f) { if (byName[name]) byName[name].fig = f; }

  /* 将棋的**标准初形**（用坐标生成，不手打 —— 手打容易错一格） */
  var INIT = (function () {
    var l = [], x;
    /* 先手：9九香 8九桂 7九銀 6九金 5九玉 4九金 3九銀 2九桂 1九香（x=0..8 依次是 9筋→1筋） */
    var back = ['L', 'N', 'S', 'G', 'K', 'G', 'S', 'N', 'L'];
    for (x = 0; x < 9; x++) l.push([x, 8, 's', back[x], 0]);
    for (x = 0; x < 9; x++) l.push([x, 6, 's', 'P', 0]);
    l.push([7, 7, 's', 'R', 0]);          /* 先手飞 2八 */
    l.push([1, 7, 's', 'B', 0]);          /* 先手角 8八 */
    /* 后手：上下对称（后手的 1一 在 x=8） */
    for (x = 0; x < 9; x++) l.push([x, 0, 'g', back[8 - x], 0]);
    for (x = 0; x < 9; x++) l.push([x, 2, 'g', 'P', 0]);
    l.push([1, 1, 'g', 'R', 0]);          /* 后手飞 8二 */
    l.push([7, 1, 'g', 'B', 0]);          /* 后手角 2二 */
    return l;
  })();

  function initWith(overrides) {
    var out = INIT.filter(function (p) {
      for (var i = 0; i < overrides.length; i++) {
        if (overrides[i][0] === p[0] && overrides[i][1] === p[1]) return false;
      }
      return true;
    });
    return out.concat(overrides);
  }

  /* 王手：先手飞在 5三，正对着后手玉 5一 */
  fig('王手', {
    list: [[4, 0, 'g', 'K', 0], [4, 2, 's', 'R', 0], [0, 8, 's', 'K', 0]],
    marks: [[4, 2]],
    cap: '先手飞车停在 5三，**正对着后手玉所在的 5一**（中间 5二 是空的）—— ' +
      '这就是王手。后手必须**当手**解决：把王挪开、吃掉这枚飞、或者在中途垫一枚驹，三者选一。' +
      '**王手本身不值钱，值钱的是「逼对方按你的节奏走」。**'
  });

  /* 詰み：先手金打到 5二，后手玉一个出口都没有 */
  fig('詰み', {
    list: [[4, 0, 'g', 'K', 0], [4, 1, 's', 'G', 0], [0, 8, 's', 'K', 0]],
    marks: [[4, 1]],
    cap: '先手金在 5二，将军。后手玉能去的格子：4一、6一、4二、6二 —— ' +
      '**这四格金都能吃到**（金比银多一个「横着走」的能力，正是靠它把 4二、6二 也封住了）。' +
      '棋盘上后手只剩这一枚玉，没人能吃掉这枚金。**这就是詰み：王手，而且无解。**'
  });

  /* 二步：同一条筋上两枚先手歩 */
  fig('二步', {
    list: [[0, 8, 's', 'K', 0], [4, 0, 'g', 'K', 0],
      [7, 3, 's', 'P', 0], [7, 4, 's', 'P', 0], [6, 5, 's', 'P', 0]],
    marks: [[7, 3], [7, 4]],
    cap: '2筋（x=7 这一列）上站着**两枚先手的歩** —— 这在将棋里是**禁手**：' +
      '同一条筋上不允许有两枚自己未升变的歩。' +
      '注意左边 3筋 上那枚歩（x=6）是正常的：**「二步」只禁同一条筋，不管别的筋上有多少枚。**'
  });

  /* 升变（成る）：先手歩走到 3三，进了敌阵 */
  fig('升变（成る）', {
    list: [[0, 8, 's', 'K', 0], [4, 0, 'g', 'K', 0],
      [6, 2, 's', 'P', 0], [8, 8, 's', 'L', 0],
      [6, 1, 's', 'P', 1], [8, 1, 's', 'L', 1]],
    marks: [[6, 2]],
    cap: '棋盘上第 1–3 段（y=0、1、2）是**敌阵**。先手歩走到 3三（标记处）就进了敌阵，' +
      '**可以选择升变为「と金」**（成った歩）。' +
      '右边两枚就是已经升变过的：成香（x=8,y=1）和 と金（x=6,y=1）—— ' +
      '升变过的驹**字会写成草书**，在盘上就是这么认的。'
  });

  /* 居飞车：飞留在右边原位（2八），王在 5九 */
  fig('居飞车', {
    list: initWith([[7, 7, 's', 'R', 0]]),
    marks: [[7, 7]],
    cap: '先手的飞车（标记处）留在**原来那一列（2筋）**没动窝 —— 这就是「居飞车」。' +
      '飞在右边不动，好处是**右边这条线随时能打开**，攻击力攒着；' +
      '缺点是自己的玉通常得往左边躲（比如 5九 移到 6八、7八），左边的守备要另花手数去搭。'
  });

  /* 振飞车：飞挪到左边（6八） */
  fig('振飞车', {
    list: initWith([[3, 7, 's', 'R', 0]]),
    marks: [[3, 7]],
    cap: '同一套初形，只是把飞车**挪到了左边 6八**（标记处）—— 这就是「振飞车」。' +
      '「振る」是把飞车横挪的意思。' +
      '飞挪到左边之后，玉就可以安安静静待在右边（2八一带）搭美濃、穴熊这类围 —— ' +
      '**先守后攻，这是两种完全不同的棋风。**'
  });

  /* 角换：双方角行对着同一条斜线 */
  fig('角换', {
    list: [[0, 8, 's', 'K', 0], [8, 0, 'g', 'K', 0],
      [1, 7, 's', 'B', 0], [7, 1, 'g', 'B', 0],
      [6, 2, 's', 'P', 0], [2, 6, 'g', 'P', 0]],
    marks: [[1, 7], [7, 1]],
    cap: '先手角在 8八、后手角在 2二 —— **两枚角走的是同一条对角线（8八→1一 这条）**。' +
      '把这条线上的歩拱开之后，双方就能互相吃角，这就是「角换」。' +
      '角换之后局面会变得很开放、很乱，**它同时也是「角换流」这一类下法的起点。**'
  });

})(typeof window !== 'undefined' ? window : (typeof globalThis !== 'undefined' ? globalThis : this));
